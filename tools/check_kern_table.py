"""kerning 表可重生成校验（`[124]` 的门 2 式）。

中文：
  表是抄字体的，生成器是写的。**字体一换，键就全部失效**——表里的键是字形 id，
  同一个 id 在另一份字体上是另一个字形，按错的 id 调字距比不调更坏（会把不该收的字距收紧）。
  所以这里做三件事：

    1. 重新跑一遍生成器，与仓内的 `.c` / `.h` **逐字节**比对；
    2. 钉住内置字体的 sha256 与对数——生成头里写着，读出来对；
    3. 表必须是**升序且无重复键**（运行期二分的前提，错了就静默查不到）。

  与 `[123]` 的 `check_hyphen_table.py` 同一个模式：表 += 生成器 += 校验，三者一起才算证据。

English:
  Re-run the flattening and compare byte-for-byte; pin the face sha256 and the pair count;
  assert the key array is strictly ascending (binary search silently fails otherwise).

用法 / usage: python3 tools/check_kern_table.py
"""
from __future__ import annotations

import hashlib
import importlib.util
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / "main/assets/builtin.ttf"
H = ROOT / "main/font/kern_pairs.h"
C = ROOT / "main/font/kern_pairs.c"

EXPECT_PAIRS = 1206
EXPECT_FONT_SHA = "1c5e1437ebd03691dea94c29ca4347c7162a8a0f1c9dad43a9a7ca8c1d9f3fb5"


def load_generator():
    spec = importlib.util.spec_from_file_location("gen_kern_table", ROOT / "tools/gen_kern_table.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    for p in (FONT, H, C):
        if not p.exists():
            print("kern-table: FAIL - 缺少 %s" % p.relative_to(ROOT))
            return 1

    font_sha = hashlib.sha256(FONT.read_bytes()).hexdigest()
    if font_sha != EXPECT_FONT_SHA:
        print("kern-table: FAIL - 内置字体变了（%s != %s）；表里的字形 id 已失效，必须重生成"
              % (font_sha[:16], EXPECT_FONT_SHA[:16]))
        return 1

    gen = load_generator()
    try:
        header, source = gen.render(FONT)
    except SystemExit as exc:  # 生成器自己的失败关闭
        print("kern-table: FAIL - 生成器拒绝出表：%s" % exc)
        return 1

    on_disk_h = H.read_text(encoding="utf-8")
    on_disk_c = C.read_text(encoding="utf-8")
    if on_disk_h != header:
        print("kern-table: FAIL - kern_pairs.h 与重新生成的结果**不是同一份**")
        return 1
    if on_disk_c != source:
        print("kern-table: FAIL - kern_pairs.c 与重新生成的结果**不是同一份**")
        return 1

    m = re.search(r"#define KERN_PAIR_COUNT (\d+)", on_disk_h)
    count = int(m.group(1)) if m else -1
    if count != EXPECT_PAIRS:
        print("kern-table: FAIL - 对数 %d != 期望 %d" % (count, EXPECT_PAIRS))
        return 1

    keys = [int(x, 16) for x in re.findall(r"0x([0-9a-f]{8})u", on_disk_c)]
    if len(keys) != count:
        print("kern-table: FAIL - 键数组 %d 项，头里写 %d 项" % (len(keys), count))
        return 1
    for i in range(1, len(keys)):
        if keys[i] <= keys[i - 1]:
            print("kern-table: FAIL - 键不是严格升序（第 %d 项 %08x <= %08x），二分查不到"
                  % (i, keys[i], keys[i - 1]))
            return 1

    print("kern-table: PASS - %d pairs, regenerated byte-identical, keys strictly ascending, "
          "font sha256 %s" % (count, font_sha[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
