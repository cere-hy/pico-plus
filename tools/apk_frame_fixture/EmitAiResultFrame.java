package dev.readpico.push;

/**
 * 产出「APK 真实线格式帧」给 C 宿主测试当 fixture（gen26.6.1 D-1 的第 2 条收口）。
 * Emit the APK's REAL wire-format frame as a fixture for the C host test
 * (gen26.6.1 D-1, closing item 2).
 *
 * 为什么必须由 Java 现产：gen26.6.1 之前，C 侧的 0x07 编解码往返用
 * `PUSH_AI_RESULT_MAX` 当缓冲——D3 把释义槽 170→768 后，缓冲随之变 839B，
 * 编/解在同一个「对端从不产出的表示」上自洽，于是 241B 冻结帧被拒的真机缺陷
 * 在宿主里永远绿。同族第三次（前有别名用字面量、量宽用错路径）：**测试用了
 * 对端从不产出的表示**。故 fixture 必须由 Java 侧真实编码器现产，手写字节一律作废。
 * Why Java must produce it: before gen26.6.1 the C round-trip used
 * `PUSH_AI_RESULT_MAX` as its buffer - after D3 widened the def slot, the buffer
 * grew to 839B and encode/decode agreed on a representation THE PEER NEVER
 * PRODUCES, so the real defect (every 241B frozen frame rejected) stayed green
 * forever. Third of a kind (after a literal-aliased call and a mismatched measure
 * path): **the test used a representation the peer never emits**. So the fixture
 * must be generated by the Java encoder; hand-written bytes are void.
 *
 * 用法 / Usage: java -cp <classes> dev.readpico.push.EmitAiResultFrame  (stdout = C header)
 */
public final class EmitAiResultFrame {

    /** 短释义（≤169B）：走 0x07 单帧——正是 D-1 里被误拒的那一路。 */
    private static final String DEF_SHORT =
            "lasting a very short time; 短暂的，转瞬即逝的。短语示例: a ephemeral trend";
    /** 正好 169 字节：0x07 单帧帽的满载边界（第 170 字节无 NUL 容身处）。 */
    private static final String DEF_169 = repeat("中", 56) + "x"; // 56*3+1 = 169

    private EmitAiResultFrame() {}

    private static String repeat(String s, int n) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < n; ++i) sb.append(s);
        return sb.toString();
    }

    private static void emit(StringBuilder o, String name, String word, String def) {
        byte[] frame = PushProto.encodeAiResult(word, def);
        o.append("/* APK PushProto.encodeAiResult(").append(quote(word)).append(", ...")
                .append(") 真实产出 / really produced by the APK: ")
                .append(frame.length).append("B, def=")
                .append(new String(def.getBytes(java.nio.charset.Charset.forName("UTF-8")),
                        java.nio.charset.Charset.forName("UTF-8")).length())
                .append("B (UTF-8 bytes) */\n");
        o.append("static const uint8_t ").append(name).append("[] = {\n    ");
        for (int i = 0; i < frame.length; ++i) {
            o.append(String.format("0x%02x", frame[i]));
            if (i + 1 < frame.length) o.append(',');
            if ((i + 1) % 12 == 0) o.append("\n    ");
            else if (i + 1 < frame.length) o.append(' ');
        }
        o.append("\n};\n");
        o.append("#define ").append(name).append("_WORD ").append(quote(word)).append('\n');
        o.append("#define ").append(name).append("_DEF ").append(quote(def)).append('\n');
        o.append('\n');
    }

    private static String quote(String s) {
        StringBuilder sb = new StringBuilder("\"");
        for (byte b : s.getBytes(java.nio.charset.Charset.forName("UTF-8"))) {
            int c = b & 0xFF;
            if (c >= 0x20 && c < 0x7F && c != '"' && c != '\\') {
                sb.append((char) c);
            } else {
                sb.append(String.format("\\%03o", c)); // 逃逸非 ASCII/引号，保持 C 字面量安全
            }
        }
        return sb.append('"').toString();
    }

    public static void main(String[] args) {
        StringBuilder o = new StringBuilder();
        o.append("/* 生成文件，勿手改 / GENERATED - DO NOT EDIT.\n");
        o.append("   由 tools/gen_apk_frame_fixture.sh 调用 Java 侧 "
                + "PushProto.encodeAiResult() 现产。\n");
        o.append("   Generated by tools/gen_apk_frame_fixture.sh from the Java-side\n");
        o.append("   PushProto.encodeAiResult(). 手写字节一律作废 / hand-written bytes are void. */\n");
        o.append("#pragma once\n\n");
        emit(o, "APK_AI_RESULT_SHORT", "respectful", DEF_SHORT);
        emit(o, "APK_AI_RESULT_169B", "boundary", DEF_169);
        System.out.print(o);
    }
}
