#!/usr/bin/env python3
"""中文：连字符模式表必须能**从源重新生成**，且生成物与提交的一字不差。
English: The hyphenation table must be reproducible from its source, byte for byte.

为什么不只查 sha256：sha 只能证明「源没变」，证明不了「表是从这个源出来的」。
有人手改一条模式、把 sha 宏留着，sha 一样过。所以这里真跑生成器，比两个文件
的字节；生成器本身若被改（比如偷偷换了左右最小切长），生成物也会变。

同时钉三个数字：模式 4,447 条、例外 14 条、源 sha256——TeX 官方 hyphen.tex 的
事实值，任何一项对不上都说明换了一份表。
"""
from __future__ import annotations

import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools/vendor/hyph-en-us.tex"
BLOB = ROOT / "main/book/hyph_en_us_data.c"
HDR = ROOT / "main/book/hyph_en_us_data.h"
GEN = ROOT / "tools/gen_hyphen_table.py"

EXPECT_SHA = "2c18acdc04c1a066aeb1759905e7ca449f0616c314b5ed6aebe55b9d4a89b8d4"
EXPECT_PATTERNS = 4447
EXPECT_EXCEPTIONS = 14


def fail(msg: str) -> int:
    print(f"hyphen-table: FAIL - {msg}")
    return 1


def main() -> int:
    if not SRC.exists():
        return fail(f"missing source {SRC.relative_to(ROOT)}")
    digest = hashlib.sha256(SRC.read_bytes()).hexdigest()
    if digest != EXPECT_SHA:
        return fail(f"source sha256 {digest[:16]} != pinned {EXPECT_SHA[:16]}")

    text = SRC.read_text(encoding="utf-8")
    # 注释先剥，否则 % 后面的英文句子会被当成模式（第一版就踩过）。
    stripped = []
    for line in text.splitlines():
        i, cut = 0, len(line)
        while i < len(line):
            if line[i] == "\\":
                i += 2
                continue
            if line[i] == "%":
                cut = i
                break
            i += 1
        stripped.append(line[:cut])
    body = "\n".join(stripped)
    patterns = re.search(r"\\patterns\{(.*?)\}", body, re.S).group(1).split()
    exceptions = re.search(r"\\hyphenation\{(.*?)\}", body, re.S).group(1).split()
    if len(patterns) != EXPECT_PATTERNS:
        return fail(f"pattern count {len(patterns)} != {EXPECT_PATTERNS}")
    if len(exceptions) != EXPECT_EXCEPTIONS:
        return fail(f"exception count {len(exceptions)} != {EXPECT_EXCEPTIONS}")

    if not BLOB.exists():
        return fail("missing generated data file")
    committed = BLOB.read_bytes()
    header = HDR.read_text(encoding="utf-8")

    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        # 生成器写死两个输出路径：拷一份到临时树里跑，避免污染工作树
        # （跑门禁不该改任何文件——树身份总闸会当场判红）。
        sandbox = tmp / "repo"
        (sandbox / "tools").mkdir(parents=True)
        (sandbox / "tools/vendor").mkdir(parents=True)
        (sandbox / "main/book").mkdir(parents=True)
        (sandbox / "tools/gen_hyphen_table.py").write_bytes(GEN.read_bytes())
        (sandbox / "tools/vendor/hyph-en-us.tex").write_bytes(SRC.read_bytes())
        r = subprocess.run([sys.executable, str(sandbox / "tools/gen_hyphen_table.py")],
                           capture_output=True, text=True)
        if r.returncode != 0:
            return fail(f"generator failed: {r.stderr.strip()[:200]}")
        fresh_c = (sandbox / "main/book/hyph_en_us_data.c").read_bytes()
        fresh_h = (sandbox / "main/book/hyph_en_us_data.h").read_text(encoding="utf-8")

    if fresh_c != committed:
        return fail("hyph_en_us_data.c differs from a fresh generation "
                    "(table hand-edited, or generator changed)")
    if fresh_h != header:
        return fail("hyph_en_us_data.h differs from a fresh generation")
    for macro, want in (("HYPH_EN_US_PATTERN_COUNT", EXPECT_PATTERNS),
                        ("HYPH_EN_US_EXCEPTION_COUNT", EXPECT_EXCEPTIONS)):
        m = re.search(rf"#define {macro} (\d+)", header)
        if not m or int(m.group(1)) != want:
            return fail(f"{macro} missing or != {want}")
    if EXPECT_SHA not in header:
        return fail("source sha256 not pinned in the header")

    kilo = len(committed) / 1024.0
    print(f"hyphen-table: PASS - {EXPECT_PATTERNS} patterns / {EXPECT_EXCEPTIONS} exceptions, "
          f"regenerated byte-identical ({kilo:.1f} KiB source of data), "
          f"source sha256 {EXPECT_SHA[:16]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
